"""Exact, exhaustive decision of every rung of the derivation tower
LS(t, t+1, t+m) for the colour counts m = 5 and m = 7.

Why this matters for Erdos-Rosenfeld #835.  At parameter k the object is the
top rung t = k-1 of the tower with m = k+1 colours, and by Theorem 9 of
collaboration/opus5/derivation_tower_obstruction/NOTE.md the rungs are
monotone: rung t implies rung t-1.  So the tower is decided by its FIRST
failing rung, and the only question that matters is where that is.  The two
smallest admissible #835 candidates, m = 5 and m = 7, can be profiled by
complete enumeration through their first failing rung.  This file does that.

Result (see the printed table):

    m = 5 : rung 1 exists, rung 2 fails  -> first failure at t = 2 (the STS rung)
    m = 7 : rungs 1,2 exist, rung 3 fails -> first failure at t = 3 (the SQS rung)

The m = 7 rung-3 value, D(10) = 5, is obtained here by complete enumeration as
an independent reproduction of the classical Kramer--Mesner result.  The
maximum number of pairwise disjoint SQS(10) is five, so LS(3,4,10) does not
exist, and hence (by tower monotonicity alone, with no further computation)
neither does LS(4,5,11) nor LS(5,6,12).  This re-proves the known exclusion of
k = 6 from a lower rung.

Everything is exhaustive and deterministic: all labelled Steiner systems are
generated by exact cover, and the maximum number of pairwise disjoint ones is
found by complete maximum-clique branch and bound on the disjointness graph.
Standard library only, no randomness, no solver, no network.
"""

from __future__ import annotations

import itertools
import json
import pathlib
import sys
import time
from math import comb, factorial

# labelled-system counts that are independently known, used as cross-checks
KNOWN_LABELLED = {
    (6, 1): 15,  # perfect matchings of K_6
    (7, 2): 30,  # Fano planes on 7 labelled points
    (8, 1): 105,  # perfect matchings of K_8
    (9, 2): 840,  # STS(9)
    (10, 3): 2520,  # SQS(10)
    (11, 4): 5040,  # S(4,5,11), the Witt design
}


def enumerate_steiner(v: int, t: int) -> list[tuple[int, ...]]:
    """Every labelled S(t, t+1, v) on [v], as sorted tuples of block indices.

    Exact cover by Algorithm X: columns are the t-subsets of [v], rows the
    (t+1)-subsets.  The column with fewest remaining rows is branched on."""
    blocks = list(itertools.combinations(range(v), t + 1))
    subs = list(itertools.combinations(range(v), t))
    sub_id = {s: i for i, s in enumerate(subs)}
    rows_of: list[list[int]] = [[] for _ in subs]
    cols_of: list[list[int]] = []
    for b in blocks:
        cs = [sub_id[s] for s in itertools.combinations(b, t)]
        cols_of.append(cs)
    for bi, cs in enumerate(cols_of):
        for c in cs:
            rows_of[c].append(bi)

    covered = [False] * len(subs)
    row_alive = [True] * len(blocks)
    count_alive = [len(rows_of[c]) for c in range(len(subs))]
    chosen: list[int] = []
    out: list[tuple[int, ...]] = []

    def pick() -> int:
        best, best_n = -1, 1 << 30
        for c in range(len(subs)):
            if not covered[c] and count_alive[c] < best_n:
                best, best_n = c, count_alive[c]
        return best

    def rec(remaining: int) -> None:
        if remaining == 0:
            out.append(tuple(sorted(chosen)))
            return
        c = pick()
        if count_alive[c] == 0:
            return
        for bi in list(rows_of[c]):
            if not row_alive[bi]:
                continue
            conflicts = set()
            for cc in cols_of[bi]:
                covered[cc] = True
                for rr in rows_of[cc]:
                    if row_alive[rr]:
                        conflicts.add(rr)
            for rr in conflicts:
                row_alive[rr] = False
                for cc2 in cols_of[rr]:
                    count_alive[cc2] -= 1
            chosen.append(bi)
            rec(remaining - (t + 1))
            chosen.pop()
            for rr in conflicts:
                row_alive[rr] = True
                for cc2 in cols_of[rr]:
                    count_alive[cc2] += 1
            for cc in cols_of[bi]:
                covered[cc] = False

    rec(len(subs))
    return out


def max_disjoint(masks: list[int]) -> tuple[int, list[int]]:
    """Exact maximum number of pairwise disjoint systems, by complete
    maximum-clique branch and bound on the disjointness graph.

    The search is exhaustive: no time limit, no early exit, no heuristic."""
    n = len(masks)
    best = 0
    best_set: list[int] = []
    cur: list[int] = []

    def rec(cands: list[int]) -> None:
        nonlocal best, best_set
        if len(cur) > best:
            best, best_set = len(cur), list(cur)
        if not cands:
            return
        # bound: nothing beyond |cur| + |cands| is reachable
        if len(cur) + len(cands) <= best:
            return
        for idx, i in enumerate(cands):
            if len(cur) + (len(cands) - idx) <= best:
                return
            mi = masks[i]
            nxt = [j for j in cands[idx + 1 :] if not (mi & masks[j])]
            cur.append(i)
            rec(nxt)
            cur.pop()

    rec(list(range(n)))
    return best, best_set


def rung(m: int, t: int, note: str = "") -> dict:
    """Decide LS(t, t+1, t+m) exactly by complete enumeration."""
    v = t + m
    start = time.time()
    systems = enumerate_steiner(v, t)
    blocks = list(itertools.combinations(range(v), t + 1))
    masks = []
    for sysblocks in systems:
        mask = 0
        for bi in sysblocks:
            mask |= 1 << bi
        masks.append(mask)

    expected = KNOWN_LABELLED.get((v, t))
    cross = "" if expected is None else ("ok" if expected == len(systems) else "MISMATCH")

    best, best_set = max_disjoint(masks)
    elapsed = time.time() - start
    exists = best >= m

    witness = [[list(blocks[bi]) for bi in systems[i]] for i in best_set]
    result = {
        "m": m,
        "t": t,
        "large_set": f"LS({t},{t+1},{v})",
        "design": f"S({t},{t+1},{v})",
        "labelled_systems": len(systems),
        "labelled_systems_cross_check": cross,
        "automorphism_group_order_implied": factorial(v) // len(systems) if systems else None,
        "blocks_per_system": len(systems[0]) if systems else 0,
        "universe_size": comb(v, t + 1),
        "members_required": m,
        "max_pairwise_disjoint": best,
        "large_set_exists": exists,
        "witness_system_indices": best_set,
        "witness": witness,
        "seconds": round(elapsed, 2),
        "note": note,
    }
    print(
        f"  m={m} t={t}  {result['large_set']:>16}: {len(systems):>6,} labelled systems"
        f"{' [' + cross + ']' if cross else ''}, "
        f"max pairwise disjoint = {best} of {m} required -> "
        f"{'EXISTS' if exists else 'DOES NOT EXIST'}   [{elapsed:.1f}s]"
    )
    return result


def validate_witness(res: dict) -> bool:
    """Independently re-check the reported maximum family from scratch."""
    v = res["t"] + res["m"]
    t = res["t"]
    systems = [[frozenset(b) for b in sysb] for sysb in res["witness"]]
    if len(systems) != res["max_pairwise_disjoint"]:
        return False
    subs = [frozenset(c) for c in itertools.combinations(range(v), t)]
    seen: set[frozenset[int]] = set()
    for system in systems:
        cover: dict[frozenset[int], int] = {s: 0 for s in subs}
        for block in system:
            if len(block) != t + 1:
                return False
            for c in itertools.combinations(sorted(block), t):
                cover[frozenset(c)] += 1
        if any(x != 1 for x in cover.values()):
            return False
        if seen & set(system):
            return False
        seen |= set(system)
    return True


def main() -> None:
    out: list[dict] = []
    print("Complete derivation-tower profiles, by exhaustive enumeration.")
    print("Rung t is LS(t, t+1, t+m); rung t implies rung t-1 (derivation),")
    print("so the tower is decided by its first failing rung.")
    print()
    print("m = 5   (k = 4; the #835 object is the top rung t = k-1 = 3)")
    out.append(rung(5, 1, "one-factorisation of K_6"))
    out.append(rung(5, 2, "five disjoint Fano planes; classical (Cayley)"))
    print()
    print("m = 7   (k = 6; the #835 object is the top rung t = k-1 = 5)")
    out.append(rung(7, 1, "one-factorisation of K_8"))
    out.append(rung(7, 2, "seven disjoint STS(9)"))
    out.append(
        rung(
            7,
            3,
            "seven disjoint SQS(10); classical D(10)=5 independently reproduced",
        )
    )

    print()
    ok = all(validate_witness(r) for r in out)
    print(f"independent re-check of every reported maximum family: {'ok' if ok else 'FAILED'}")
    cross_ok = all(r["labelled_systems_cross_check"] in ("", "ok") for r in out)
    print(f"labelled-system counts against known values: {'ok' if cross_ok else 'MISMATCH'}")

    print()
    print("Consequences that need no further computation (tower monotonicity):")
    print("  m=5: rung 2 fails  => rungs 3.. fail  => k=4 excluded")
    print("  m=7: rung 3 fails  => rungs 4,5 fail  => k=6 excluded")
    print("       in particular LS(4,5,11) and LS(5,6,12) do not exist.")
    print()
    print("First failing rung:  m=5 -> t=2 (STS rung).   m=7 -> t=3 (SQS rung).")
    print("For m=17 the STS rung t=2 (LS(2,3,19)) EXISTS, and the SQS rung")
    print("t=3 (LS(3,4,20)) is exactly the open frontier.")

    path = pathlib.Path(__file__).with_name("tower_profile.json")
    path.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
    print(f"\nwrote {path.name}")
    sys.exit(0 if (ok and cross_ok) else 1)


if __name__ == "__main__":
    sys.setrecursionlimit(100000)
    main()
