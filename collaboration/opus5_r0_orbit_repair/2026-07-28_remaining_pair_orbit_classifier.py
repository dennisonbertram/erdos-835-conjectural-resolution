#!/usr/bin/env python3
"""Exact compatible-pair orbit classifier for support orbits 4 through 15.

For each Venn orbit, choose lexicographically the pair of omitted triples
with maximum intersection.  Enumerate every edge-disjoint pair of perfect
matchings on the complementary ten-vertex supports.

The primary classifier is a canonical multiset of alternating
path/cycle component words.  Words record the full three-row Venn-cell mask
of every vertex and the matching colour of every edge.  They are quotiented
by path reversal, coloured-cycle dihedral symmetry, every row symmetry of
the three-support system that stabilizes the selected unordered pair, and
an optional swap of the two matching colours.

An independent exhaustive audit builds the action graph generated by
within-cell adjacent transpositions and canonical representatives of all
allowed row symmetries.  Its connected components must agree exactly with
the component-word invariant buckets.
"""

from __future__ import annotations

import argparse
from array import array
from functools import lru_cache
from itertools import combinations, permutations, product


VERTICES = tuple(range(13))
EDGES = tuple(combinations(VERTICES, 2))
EDGE_INDEX = {edge: index for index, edge in enumerate(EDGES)}
ROW_INDICES = (0, 1, 2)
CELL_MASKS = tuple(range(1, 8))


def edge(left: int, right: int) -> tuple[int, int]:
    return tuple(sorted((left, right)))


def transform_mask(mask: int, row_permutation: tuple[int, ...]) -> int:
    """Apply an old-row -> new-row permutation to a Venn mask."""
    return sum(((mask >> old) & 1) << row_permutation[old] for old in ROW_INDICES)


def transformed_signature(
    signature: tuple[int, ...],
    row_permutation: tuple[int, ...],
) -> tuple[int, ...]:
    result = [0] * 7
    for old_mask, count in zip(CELL_MASKS, signature):
        new_mask = transform_mask(old_mask, row_permutation)
        result[new_mask - 1] = count
    return tuple(result)


def canonical_signature(signature: tuple[int, ...]) -> tuple[int, ...]:
    return min(
        transformed_signature(signature, row_permutation)
        for row_permutation in permutations(ROW_INDICES)
    )


def venn_signatures() -> tuple[tuple[int, ...], ...]:
    signatures = set()
    for candidate in product(range(4), repeat=7):
        if any(
            sum(candidate[mask - 1] for mask in CELL_MASKS if mask & (1 << row)) != 3
            for row in ROW_INDICES
        ):
            continue
        if sum(candidate) <= len(VERTICES):
            signatures.add(canonical_signature(candidate))
    result = tuple(sorted(signatures))
    assert len(result) == 16
    return result


def representative(signature: tuple[int, ...]) -> tuple[frozenset[int], ...]:
    vertices_by_mask: dict[int, tuple[int, ...]] = {}
    next_vertex = 0
    for mask in (1, 3, 5, 7, 2, 4, 6):
        count = signature[mask - 1]
        vertices_by_mask[mask] = tuple(range(next_vertex, next_vertex + count))
        next_vertex += count
    rows = tuple(
        frozenset(
            vertex
            for mask, vertices in vertices_by_mask.items()
            if mask & (1 << row)
            for vertex in vertices
        )
        for row in ROW_INDICES
    )
    assert all(len(row) == 3 for row in rows)
    return rows


def vertex_masks(rows: tuple[frozenset[int], ...]) -> tuple[int, ...]:
    return tuple(
        sum((1 << row) if vertex in rows[row] else 0 for row in ROW_INDICES)
        for vertex in VERTICES
    )


def maximum_intersection_pair(
    rows: tuple[frozenset[int], ...],
) -> tuple[int, int]:
    sizes = {
        pair: len(rows[pair[0]] & rows[pair[1]])
        for pair in combinations(ROW_INDICES, 2)
    }
    maximum = max(sizes.values())
    return min(pair for pair, size in sizes.items() if size == maximum)


@lru_cache(maxsize=None)
def perfect_matchings(vertices: tuple[int, ...]) -> tuple[tuple[int, ...], ...]:
    if not vertices:
        return ((),)
    first = vertices[0]
    result = []
    for position in range(1, len(vertices)):
        second = vertices[position]
        rest = vertices[1:position] + vertices[position + 1 :]
        edge_index = EDGE_INDEX[edge(first, second)]
        for tail in perfect_matchings(rest):
            result.append(tuple(sorted((edge_index, *tail))))
    return tuple(result)


def matching_mask(matching: tuple[int, ...]) -> int:
    return sum(1 << edge_index for edge_index in matching)


def row_symmetries(
    signature: tuple[int, ...],
    selected_pair: tuple[int, int],
) -> tuple[tuple[int, ...], ...]:
    pair_set = set(selected_pair)
    result = tuple(
        row_permutation
        for row_permutation in permutations(ROW_INDICES)
        if transformed_signature(signature, row_permutation) == signature
        and {row_permutation[index] for index in selected_pair} == pair_set
    )
    assert tuple(ROW_INDICES) in result
    return result


def component_orientations(
    kind: int,
    masks: tuple[int, ...],
    colours: tuple[int, ...],
) -> tuple[tuple[int, tuple[int, ...], tuple[int, ...]], ...]:
    """All path/cycle presentations preserving the coloured component."""
    if kind == 0:
        assert len(colours) + 1 == len(masks)
        return (
            (kind, masks, colours),
            (kind, tuple(reversed(masks)), tuple(reversed(colours))),
        )

    assert kind == 1 and len(colours) == len(masks)
    size = len(masks)
    result = []
    for start in range(size):
        forward_masks = tuple(masks[(start + offset) % size] for offset in range(size))
        forward_colours = tuple(
            colours[(start + offset) % size] for offset in range(size)
        )
        result.append((kind, forward_masks, forward_colours))

        reverse_masks = tuple(masks[(start - offset) % size] for offset in range(size))
        reverse_colours = tuple(
            colours[(start - offset - 1) % size] for offset in range(size)
        )
        result.append((kind, reverse_masks, reverse_colours))
    return tuple(result)


@lru_cache(maxsize=None)
def canonical_component(
    kind: int,
    masks: tuple[int, ...],
    colours: tuple[int, ...],
) -> tuple[int, tuple[int, ...], tuple[int, ...]]:
    return min(component_orientations(kind, masks, colours))


def decompose_pair(
    left_matching: tuple[int, ...],
    right_matching: tuple[int, ...],
    selected_pair: tuple[int, int],
    masks: tuple[int, ...],
) -> tuple[tuple[int, tuple[int, ...], tuple[int, ...]], ...]:
    """Return identity-canonical alternating component words."""
    left_colour, right_colour = selected_pair
    adjacency: list[list[tuple[int, int]]] = [[] for _ in VERTICES]
    for matching, colour in (
        (left_matching, left_colour),
        (right_matching, right_colour),
    ):
        for edge_index in matching:
            left, right = EDGES[edge_index]
            adjacency[left].append((right, colour))
            adjacency[right].append((left, colour))

    for vertex in VERTICES:
        expected_colours = sorted(
            colour for colour in selected_pair if not (masks[vertex] & (1 << colour))
        )
        actual_colours = sorted(colour for _, colour in adjacency[vertex])
        assert actual_colours == expected_colours
        assert len({neighbour for neighbour, _ in adjacency[vertex]}) == len(
            adjacency[vertex]
        )

    used = {vertex for vertex in VERTICES if adjacency[vertex]}
    unseen = set(used)
    components = []
    while unseen:
        seed = min(unseen)
        component = {seed}
        stack = [seed]
        while stack:
            vertex = stack.pop()
            for neighbour, _ in adjacency[vertex]:
                if neighbour not in component:
                    component.add(neighbour)
                    stack.append(neighbour)
        unseen -= component

        endpoints = sorted(
            vertex for vertex in component if len(adjacency[vertex]) == 1
        )
        if endpoints:
            assert len(endpoints) == 2
            kind = 0
            start = endpoints[0]
            previous = -1
            current = start
            ordered_vertices = [current]
            ordered_colours = []
            while True:
                choices = [
                    (neighbour, colour)
                    for neighbour, colour in adjacency[current]
                    if neighbour != previous
                ]
                if not choices:
                    break
                assert len(choices) == 1
                following, colour = choices[0]
                ordered_colours.append(colour)
                ordered_vertices.append(following)
                previous, current = current, following
        else:
            assert all(len(adjacency[vertex]) == 2 for vertex in component)
            kind = 1
            start = min(component)
            following, first_colour = min(adjacency[start])
            previous = start
            current = following
            ordered_vertices = [start, current]
            ordered_colours = [first_colour]
            while current != start:
                choices = [
                    (neighbour, colour)
                    for neighbour, colour in adjacency[current]
                    if neighbour != previous
                ]
                assert len(choices) == 1
                following, colour = choices[0]
                ordered_colours.append(colour)
                previous, current = current, following
                if current != start:
                    ordered_vertices.append(current)
            assert len(ordered_colours) == len(ordered_vertices)

        mask_word = tuple(masks[vertex] for vertex in ordered_vertices)
        components.append(canonical_component(kind, mask_word, tuple(ordered_colours)))
    return tuple(sorted(components))


def pair_invariant(
    components: tuple[tuple[int, tuple[int, ...], tuple[int, ...]], ...],
    symmetries: tuple[tuple[int, ...], ...],
) -> tuple[tuple[int, tuple[int, ...], tuple[int, ...]], ...]:
    candidates = []
    for row_permutation in symmetries:
        transformed = []
        for kind, masks, colours in components:
            transformed.append(
                canonical_component(
                    kind,
                    tuple(transform_mask(mask, row_permutation) for mask in masks),
                    tuple(row_permutation[colour] for colour in colours),
                )
            )
        candidates.append(tuple(sorted(transformed)))
    return min(candidates)


def canonical_vertex_permutation(
    masks: tuple[int, ...],
    row_permutation: tuple[int, ...],
) -> tuple[int, ...]:
    cells = {
        mask: tuple(vertex for vertex in VERTICES if masks[vertex] == mask)
        for mask in range(8)
    }
    result = [-1] * len(VERTICES)
    for old_mask, old_vertices in cells.items():
        new_vertices = cells[transform_mask(old_mask, row_permutation)]
        assert len(old_vertices) == len(new_vertices)
        for old_vertex, new_vertex in zip(old_vertices, new_vertices):
            result[old_vertex] = new_vertex
    assert sorted(result) == list(VERTICES)
    return tuple(result)


def transposition(left: int, right: int) -> tuple[int, ...]:
    result = list(VERTICES)
    result[left], result[right] = result[right], result[left]
    return tuple(result)


def transformed_matching(
    matching: tuple[int, ...],
    vertex_permutation: tuple[int, ...],
) -> tuple[int, ...]:
    return tuple(
        sorted(
            EDGE_INDEX[
                edge(
                    vertex_permutation[EDGES[index][0]],
                    vertex_permutation[EDGES[index][1]],
                )
            ]
            for index in matching
        )
    )


def action_generators(
    masks: tuple[int, ...],
    selected_pair: tuple[int, int],
    symmetries: tuple[tuple[int, ...], ...],
    families: dict[int, tuple[tuple[int, ...], ...]],
) -> tuple[tuple[str, tuple[int, ...], tuple[int, ...], bool], ...]:
    """Return distinct actions on the ordered matching-pair state space."""
    identity_rows = tuple(ROW_INDICES)
    candidates = []
    for mask in range(8):
        cell = tuple(vertex for vertex in VERTICES if masks[vertex] == mask)
        for position in range(len(cell) - 1):
            candidates.append(
                (
                    f"cell_{mask}_{position}",
                    transposition(cell[position], cell[position + 1]),
                    identity_rows,
                )
            )
    for index, row_permutation in enumerate(symmetries):
        if row_permutation != identity_rows:
            candidates.append(
                (
                    f"row_symmetry_{index}",
                    canonical_vertex_permutation(masks, row_permutation),
                    row_permutation,
                )
            )

    left_colour, right_colour = selected_pair
    family_indices = {
        colour: {matching: index for index, matching in enumerate(family)}
        for colour, family in families.items()
    }
    distinct = {}
    for name, vertex_permutation, row_permutation in candidates:
        maps = {}
        for source_colour in selected_pair:
            target_colour = row_permutation[source_colour]
            maps[source_colour] = tuple(
                family_indices[target_colour][
                    transformed_matching(matching, vertex_permutation)
                ]
                for matching in families[source_colour]
            )
        swaps = row_permutation[left_colour] == right_colour
        action = (
            maps[left_colour],
            maps[right_colour],
            swaps,
        )
        if (
            not swaps
            and all(index == image for index, image in enumerate(action[0]))
            and all(index == image for index, image in enumerate(action[1]))
        ):
            continue
        distinct.setdefault(action, name)
    return tuple(
        (name, left_map, right_map, swaps)
        for (left_map, right_map, swaps), name in distinct.items()
    )


def find(parent: array, item: int) -> int:
    root = item
    while parent[root] != root:
        root = parent[root]
    while parent[item] != item:
        following = parent[item]
        parent[item] = root
        item = following
    return root


def union(parent: array, ranks: bytearray, left: int, right: int) -> None:
    left_root = find(parent, left)
    right_root = find(parent, right)
    if left_root == right_root:
        return
    if ranks[left_root] < ranks[right_root]:
        left_root, right_root = right_root, left_root
    parent[right_root] = left_root
    if ranks[left_root] == ranks[right_root]:
        ranks[left_root] += 1


def classify_orbit(
    orbit: int,
    signature: tuple[int, ...],
    *,
    verify_generators: bool,
) -> dict[str, object]:
    rows = representative(signature)
    masks = vertex_masks(rows)
    selected_pair = maximum_intersection_pair(rows)
    left_colour, right_colour = selected_pair
    supports = {
        colour: tuple(sorted(set(VERTICES) - rows[colour])) for colour in selected_pair
    }
    families = {colour: perfect_matchings(supports[colour]) for colour in selected_pair}
    assert all(len(family) == 945 for family in families.values())
    family_masks = {
        colour: tuple(map(matching_mask, family)) for colour, family in families.items()
    }
    symmetries = row_symmetries(signature, selected_pair)

    size = 945
    state_codes = array("i")
    state_positions = array("i", [-1]) * (size * size)
    invariant_ids = array("i")
    invariants: dict[tuple, int] = {}
    for left_index, left_mask in enumerate(family_masks[left_colour]):
        for right_index, right_mask in enumerate(family_masks[right_colour]):
            if left_mask & right_mask:
                continue
            code = left_index * size + right_index
            state_positions[code] = len(state_codes)
            state_codes.append(code)
            components = decompose_pair(
                families[left_colour][left_index],
                families[right_colour][right_index],
                selected_pair,
                masks,
            )
            invariant = pair_invariant(components, symmetries)
            invariant_id = invariants.setdefault(invariant, len(invariants))
            invariant_ids.append(invariant_id)

    generator_count = 0
    generator_orbits = None
    if verify_generators:
        generators = action_generators(
            masks,
            selected_pair,
            symmetries,
            families,
        )
        generator_count = len(generators)
        parent = array("i", range(len(state_codes)))
        ranks = bytearray(len(state_codes))
        for _, left_map, right_map, swaps in generators:
            for position, code in enumerate(state_codes):
                left_index, right_index = divmod(code, size)
                transformed_left = left_map[left_index]
                transformed_right = right_map[right_index]
                if swaps:
                    transformed_left, transformed_right = (
                        transformed_right,
                        transformed_left,
                    )
                transformed_code = transformed_left * size + transformed_right
                transformed_position = state_positions[transformed_code]
                assert transformed_position >= 0
                assert invariant_ids[position] == invariant_ids[transformed_position]
                union(parent, ranks, position, transformed_position)

        invariant_roots = {}
        root_invariants = {}
        for position, invariant_id in enumerate(invariant_ids):
            root = find(parent, position)
            old_root = invariant_roots.setdefault(invariant_id, root)
            assert old_root == root
            old_invariant = root_invariants.setdefault(root, invariant_id)
            assert old_invariant == invariant_id
        generator_orbits = len(root_invariants)
        assert generator_orbits == len(invariants)

    intersections = tuple(
        len(rows[left] & rows[right]) for left, right in combinations(ROW_INDICES, 2)
    )
    return {
        "orbit": orbit,
        "signature": signature,
        "rows": tuple(tuple(sorted(row)) for row in rows),
        "pair": selected_pair,
        "pair_intersection": len(rows[left_colour] & rows[right_colour]),
        "all_intersections": intersections,
        "row_symmetries": len(symmetries),
        "disjoint_matching_pairs": len(state_codes),
        "canonical_pair_orbits": len(invariants),
        "action_generators": generator_count,
        "generator_orbits": generator_orbits,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--orbits",
        nargs="*",
        type=int,
        default=tuple(range(4, 16)),
    )
    parser.add_argument(
        "--skip-generator-audit",
        action="store_true",
        help="classify all pairs but omit the independent action-graph audit",
    )
    args = parser.parse_args()
    if any(not 4 <= orbit <= 15 for orbit in args.orbits):
        parser.error("orbits must lie between 4 and 15")

    signatures = venn_signatures()
    for orbit in args.orbits:
        result = classify_orbit(
            orbit,
            signatures[orbit],
            verify_generators=not args.skip_generator_audit,
        )
        print(result, flush=True)


if __name__ == "__main__":
    main()
